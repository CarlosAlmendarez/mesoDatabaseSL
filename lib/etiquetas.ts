const FN: Record<string, string> = {
  suma: "Suma de",
  promedio: "Promedio de",
  minimo: "Mínimo de",
  maximo: "Máximo de",
  distintos: "Distintos de",
  pct_si: "% Sí de",
};

export function etiqueta(col: string): string {
  if (ETIQUETAS[col]) return ETIQUETAS[col];
  const m = col.match(/^(suma|promedio|minimo|maximo|distintos|pct_si)_(.+)$/);
  if (m) return `${FN[m[1]]} ${etiqueta(m[2]).toLowerCase()}`;
  const t = col.replace(/^p_/, "").replace(/_/g, " ");
  return t.charAt(0).toUpperCase() + t.slice(1);
}

/** Etiqueta de un ciclo: «24-1 · ago–dic 2023» (el -1 empieza en agosto del año anterior). */
export function etiquetaCiclo(clave: string): string {
  const m = clave.match(/^(\d{2})-(\d)$/);
  if (!m) return clave;
  const yy = Number(m[1]);
  const anio = (yy >= 90 ? 1900 : 2000) + yy;
  return m[2] === "1" ? `${clave} · ago–dic ${anio - 1}` : `${clave} · ene–jul ${anio}`;
}
